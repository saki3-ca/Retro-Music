// Generates src/emoji-data.js: a word -> emoji map from emojilib keywords.
// Run with: node scripts/build-emoji.mjs   (emojilib is a devDependency, not shipped)
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const lib = require("emojilib");

const STOP = new Set(("the and but for you your yours our out not are was were has had have his her him she they them their then than " +
  "that this these those with from into onto over under about after before again also just only very much many some any all can will " +
  "get got let say said see saw way new old one two too yes now how why who what when where which while would could should shall " +
  "like make made take took come came gone going goes does did done been being here there still even ever never always every each " +
  "other another more most less least such own same off down back away cause cuz gonna wanna gotta ain yeah huh hey oh uh ooh").split(" "));

const best = {}; // word -> { score, emoji }
const put = (word, emoji, score) => {
  if (score < 3) return;
  if (word.length < 3 || STOP.has(word) || !/^[a-z]+$/.test(word)) return;
  if (!best[word] || score > best[word].score) best[word] = { score, emoji };
};

for (const emoji of Object.keys(lib)) {
  const kws = lib[emoji];
  if (!kws || !kws.length) continue;
  const name = kws[0];
  if (/^(flag_|keycap|regional)/.test(name)) continue;
  const tokens = name.split("_");
  if (tokens.length === 1) put(tokens[0], emoji, 4);
  else if (tokens.length === 2) put(tokens[1], emoji, 2.5); // e.g. light_bulb -> bulb
  kws.slice(1, 5).forEach((k, i) => {
    if (/[\s_:]/.test(k)) return;
    put(k.toLowerCase(), emoji, i < 2 ? 3 : 1.5);
  });
}

const out = {};
Object.keys(best).sort().forEach((w) => { out[w] = best[w].emoji; });
writeFileSync(new URL("../src/emoji-data.js", import.meta.url),
  "// GENERATED by scripts/build-emoji.mjs. Do not edit by hand.\nexport default " + JSON.stringify(out) + ";\n");
console.log("words:", Object.keys(out).length);
for (const w of ["light", "lights", "flight", "flashing", "flash", "shoes", "shoe", "car", "cars", "fire", "love", "heart", "star", "stars", "money", "phone", "night", "sun", "moon", "dance", "know", "believe", "wood", "floors", "apartment", "shootin"]) console.log(w, out[w] || "-");
